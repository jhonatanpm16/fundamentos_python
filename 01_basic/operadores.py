# Operadores aritmeticos

x = 5
y = 12

# Suma +
print("suma", x + y)

# Resta -
print("Resta", x - y)

# Multiplicación *
print(("Multiplicación", x * y))

# División / (Retorna un float)
print("División", y / x)

# Modulo %
print("Modulo(resto)", y % x)

# Potencia **
print("Potencia", y ** x)

# División //
print("División(entera)", y // x)

# numero par
par = 8
print(par % 2 == 0)

